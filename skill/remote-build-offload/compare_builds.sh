#!/bin/bash
# compare_builds.sh <ref_build_dir> <new_build_dir>: block design files (byte / modulo timestamp-and-path lines),
# hwh, address map, utilization (LUT/FF/BRAM/URAM/DSP) and timing from SUMMARY.txt.
# Layout expected in each build dir: bd/m7_pl/..., m7_pl.hwh, address_map.csv, utilization_route.rpt, timing_route.rpt, SUMMARY.txt
# (rename the m7_pl / clock names below to your design). PATH_RE: extra regex of path/host lines to ignore when normalising.
# Calibrate before use: (1) compare a build with itself -> all IDENTICAL; (2) compare two builds known to differ -> DIFFERS shows up.
A=${1:?ref}; B=${2:?new}
norm() { grep -v -E 'Date|date|Generated by|Tool Version|timestamp|TIMESTAMP|Copyright|'"${PATH_RE:-/home/|/tmp/|/data[0-9]*/|/opt/}"'|Host *:|Command *:|Vivado v20|SW Build|IP Build|BOARD.*PATH' "$1"; }
for f in bd/m7_pl/m7_pl.bd bd/m7_pl/synth/m7_pl.v bd/m7_pl/hdl/m7_pl_wrapper.v m7_pl.hwh address_map.csv; do
  if [ ! -f "$A/$f" ] || [ ! -f "$B/$f" ]; then echo "$f: MISSING (ref=$([ -f $A/$f ] && echo y || echo n) new=$([ -f $B/$f ] && echo y || echo n))"; continue; fi
  if cmp -s "$A/$f" "$B/$f"; then echo "$f: IDENTICAL"
  elif diff -q <(norm "$A/$f") <(norm "$B/$f") >/dev/null; then echo "$f: same modulo timestamp/path/version lines ($(diff "$A/$f" "$B/$f" | grep -c '^<') lines differ raw)"
  else echo "$f: DIFFERS ($(diff <(norm "$A/$f") <(norm "$B/$f") | grep -c '^<') lines after normalisation)"; fi
done
util() { awk -F'|' -v k="$2" '$2 ~ "^ *"k" *$" {gsub(/ /,"",$3); print $3; exit}' "$1/utilization_route.rpt"; }
printf '%-18s %12s %12s %8s\n' resource ref new diff%
for k in "CLB LUTs" "CLB Registers" "Block RAM Tile" "URAM" "DSPs"; do
  a=$(util $A "$k"); b=$(util $B "$k")
  printf '%-18s %12s %12s %8s\n' "$k" "$a" "$b" "$(awk -v a=$a -v b=$b 'BEGIN{ if (a>0) printf "%.2f", (b-a)*100/a; else print "-"}')"
done
for k in setup_wns_ns hold_whs_ns setup_wns_clk_pl_0_ns setup_wns_clk_pl_1_ns setup_wns_clk_dpu_m7_pl_clk_wiz_dpu_0_ns setup_wns_clk_dsp_m7_pl_clk_wiz_dpu_0_ns clk1_mhz_actual; do
  printf '%-44s %10s %10s\n' $k "$(sed -n "s/^$k=//p" $A/SUMMARY.txt)" "$(sed -n "s/^$k=//p" $B/SUMMARY.txt)"
done
grep -q 'All user specified timing constraints are met' "$B/timing_route.rpt" && echo "new timing_route.rpt: All user specified timing constraints are met" || echo "new timing_route.rpt: constraints NOT met (or missing)"
