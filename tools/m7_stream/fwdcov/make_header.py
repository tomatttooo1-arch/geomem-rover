#!/usr/bin/env python3
"""FWD_COV: write tb_frame_stream_fwdcov.h for tb_frame_stream.cpp from a frame pack
(make_frames.py) and the Dlat2 flags of the reference simulator for it
(G1d g1d_ref with G1D_DUMP_DLAT2, 32768 bytes per frame).
Depth is stored as the raw uint16 (mm) and the unit; the bench converts with the
same float32 rule as G1d crop.py / g1d_ref (raw * unit in float32, raw 0 -> NaN).
Expected flags are stored sparse: one uint16 per non-zero cell, index | 0x8000
for HIT (2), plain index for FREE (1).
usage: make_header.py PACK EXPECT NAMES OUT.h"""
import hashlib
import struct
import sys

pack, expect, names, out = sys.argv[1:5]
b = open(pack, "rb").read()
e = open(expect, "rb").read()
nm = open(names).read().split()
assert b[:8] == b"FPGAGPK01"
n = struct.unpack_from("<I", b, 12)[0]
assert n == len(nm) and len(e) == 32768 * n
L = []
L.append("// GENERATED by tools/m7_stream/fwdcov/make_header.py -- do not edit.")
L.append(f"// pack sha256 {hashlib.sha256(b).hexdigest()}")
L.append(f"// Dlat2 reference flags sha256 {hashlib.sha256(e).hexdigest()} (G1d g1d_ref, variant Dlat2)")
L.append("// Forwarding-coverage frames of the Dlat2 decision (see tb_frame_stream.cpp).")
L.append("#pragma once")
L.append("#include <cstdint>")
L.append("struct FwdcovFrame {")
L.append("    const char* name;")
L.append("    std::uint32_t w, h, nx, ny, nz;")
L.append("    float unit, ik[9], wc[12];")
L.append("    double origin[3], voxel;")
L.append("    const std::uint16_t* depth_raw;")
L.append("    std::uint32_t n_marked;")
L.append("    const std::uint16_t* marked;")
L.append("};")
off = 24
recs = []
for i in range(n):
    w, h, nx, ny, nz, _ = struct.unpack_from("<6I", b, off)
    unit = struct.unpack_from("<f", b, off + 24)[0]
    ik = struct.unpack_from("<9f", b, off + 28)
    wc = struct.unpack_from("<12f", b, off + 64)
    org = struct.unpack_from("<3d", b, off + 112)
    vox = struct.unpack_from("<d", b, off + 136)[0]
    raw = struct.unpack_from(f"<{w*h}H", b, off + 144)
    off += 144 + w * h * 2
    fl = e[32768 * i:32768 * (i + 1)]
    assert all(x in (0, 1, 2) for x in fl), "expect has bytes other than 0/1/2"
    mk = [j | (0x8000 if fl[j] == 2 else 0) for j in range(32768) if fl[j]]

    L.append(f"static const std::uint16_t fwdcov_depth_{i}[{w*h}] = {{")
    for k in range(0, len(raw), 24):
        L.append("    " + ", ".join(str(x) for x in raw[k:k + 24]) + ",")
    L.append("};")
    L.append(f"static const std::uint16_t fwdcov_marked_{i}[{max(len(mk),1)}] = {{")
    for k in range(0, len(mk), 16):
        L.append("    " + ", ".join(f"0x{x:04x}" for x in mk[k:k + 16]) + ",")
    if not mk:
        L.append("    0")
    L.append("};")
    recs.append((nm[i], w, h, nx, ny, nz, unit, ik, wc, org, vox, i, len(mk)))
L.append(f"static const FwdcovFrame fwdcov_frames[{n}] = {{")


def ff(x):
    # decimal literal that rounds back to exactly this float32 (repr of the exact double value)
    v = struct.unpack('<f', struct.pack('<f', x))[0]
    s = repr(float(v))
    return (s if ("." in s or "e" in s) else s + ".0") + "f"


def fd(x):
    s = repr(float(x))
    return s if ("." in s or "e" in s) else s + ".0"


for (name, w, h, nx, ny, nz, unit, ik, wc, org, vox, i, nmk) in recs:
    L.append(f'    {{"{name}", {w}, {h}, {nx}, {ny}, {nz}, {ff(unit)},')
    L.append("     {" + ", ".join(ff(x) for x in ik) + "},")
    L.append("     {" + ", ".join(ff(x) for x in wc) + "},")
    L.append("     {" + ", ".join(fd(x) for x in org) + f"}}, {fd(vox)},")
    L.append(f"     fwdcov_depth_{i}, {nmk}, fwdcov_marked_{i}}},")
L.append("};")
L.append(f"static const int fwdcov_nframes = {n};")
open(out, "w").write("\n".join(L) + "\n")
print("wrote", out, "frames", n, "marked", [r[-1] for r in recs])
