// Generates ar_overlay_lut.inc (committed) from the UNCHANGED legacy
// depth_colour() in display_overlay.cpp, so the new core's pseudo-colour is
// the old piecewise formula sampled at each 32 mm segment centre.
//   g++ -std=c++11 -O2 -I hw/m7 hw/m7/ar_overlay_lut_gen.cpp -o /tmp/gen
//   /tmp/gen > hw/m7/ar_overlay_lut.inc
// Entry i covers z in [32i, 32i+31]; it is sampled at min(32i+16, 9999)
// because the centre of segment 312 (10000) is black under the old formula.
// Entries 0..2 are never used (z < 100 is rejected first) and are 0.
#include <cstdio>
#include "display_overlay.cpp"

int main() {
    std::printf("// GENERATED by hw/m7/ar_overlay_lut_gen.cpp -- do not edit.\n");
    std::printf("// 313 entries, index = z_mm >> 5, sample = min(32*i+16, 9999).\n");
    for (unsigned i = 0; i <= 312; ++i) {
        unsigned z = 32 * i + 16;
        if (z > 9999) z = 9999;
        const unsigned v = i < 3 ? 0u : depth_colour(static_cast<std::uint16_t>(z));
        std::printf("0x%06Xu,%s", v, (i % 8 == 7) ? "\n" : " ");
    }
    std::printf("\n");
    return 0;
}
