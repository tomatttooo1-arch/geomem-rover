import { chromium } from 'playwright-core';
const [base, shot] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '${FPGA_HOME}/dev1/tmp/chrome/chrome-headless-shell-linux64/chrome-headless-shell', args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const p = await (await b.newContext({ viewport: { width: 1920, height: 1080 } })).newPage();
p.on('pageerror', e => console.log('pageerror:', e.message)); p.on('console', m => { if (m.type()==='error'||m.type()==='warning') console.log('console:', m.text()); });
await p.goto(base, { waitUntil: 'networkidle' }); await p.waitForTimeout(2500);
const t = id => p.locator('#'+id).innerText().catch(()=>null);
console.log(JSON.stringify({pill: await t('connection-pill'), fallback: await p.locator('#map-fallback').isHidden(), objs: await t('metric-objects'), sugg: await t('suggestions'), cards: await t('objects-grid')}));
await p.screenshot({ path: shot + '_1.png' });
await p.fill('#search-input', '杯子'); await p.click('#find-button'); await p.waitForTimeout(300);
console.log('results:', await t('search-results'));
await p.click('[data-find]'); await p.waitForTimeout(800);
console.log('task:', await t('task-state'), '|', await t('task-candidates'), '| pause in DOM:', await p.locator('#pause-task').count());
await p.screenshot({ path: shot + '_2.png' });
await p.click('[data-candidate="cup-02"]'); await p.waitForTimeout(4500);
console.log('task:', await t('task-state'), '|', await t('task-target'), '|', await t('task-steps'), '| pause:', await p.locator('#pause-task').count());
await p.click('#pause-task'); await p.waitForTimeout(600);
console.log('paused:', await t('task-state'), await t('metric-robot'), await t('task-steps'));
await p.screenshot({ path: shot + '_3.png' });
await p.click('#stop-task'); await p.waitForTimeout(600);
console.log('stopped:', await t('task-state'), await t('task-steps'), await t('toast'));
await p.click('[data-object="bag-01"]'); await p.waitForTimeout(500);
console.log('detail:', await t('detail-body'), '|', await t('start-task'), '|', await t('start-note'));
await p.click('#start-task'); await p.waitForTimeout(20000);
console.log('after single find:', await t('task-state'), await t('task-target'), await t('toast'));
await p.click('[data-page="history"]'); await p.waitForTimeout(800); console.log('history:', await t('history-list'));
await p.screenshot({ path: shot + '_4.png' });
await b.close();
